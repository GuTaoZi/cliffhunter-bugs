#!/usr/bin/env python3
"""Tables of data/runs.jsonl by config and arm: mean, sd, min-max of each metric. Writes results.md."""
import json
import os
import statistics as st

D = os.path.dirname(os.path.abspath(__file__))
runs = [json.loads(l) for l in open(os.path.join(D, "data", "runs.jsonl")) if l.strip()]
M = [("sets_ok", "%.0f"), ("sets_oom", "%.0f"), ("oom_frac", "%.3f"), ("oom_in_first_119", "%.0f"),
     ("first_ok_index", "%s"),
     ("outofmemory_delta", "%.0f"), ("evicted_delta", "%.0f"), ("tailrepairs_delta", "%.0f"),
     ("lat_mean_us", "%.1f"), ("lat_p50_us", "%.1f"), ("lat_p99_us", "%.1f"), ("lat_max_us", "%.0f"),
     ("sets_per_s", "%.0f"), ("write_wall_s", "%.3f"),
     ("server_cpu_s", "%.3f"), ("server_peak_rss_mb", "%.1f"),
     ("hang_get_hits", "%.0f"), ("hang_sendq_bytes", "%.0f"), ("hang_sendq_after_bytes", "%.0f"),
     ("new_key_hits_last100", "%.0f"), ("recovery_ok_of_50", "%.0f"),
     ("fill_curr_items", "%.0f"), ("fill_evictions", "%.0f")]
out = ["# memcached stuck-tail blockers: parent 4234cbad76c9 vs fix f2a4e5b491ed", "",
       "Generated by tables.py from data/runs.jsonl. mean, sd [min, max] over repetitions; "
       "server CPU and peak RSS cover the measured write phase only.", ""]
for cfg in ["refhang", "thousands-fresh", "thousands-aged"]:
    rs = [r for r in runs if r["config"] == cfg]
    if not rs:
        continue
    c0 = rs[0]
    out += [f"## {cfg}", "",
            f"-m {c0['mem']}, value {c0['vsize']} B, fill {c0['nfill']} keys, hang client multi-gets "
            f"{c0['nhang']} keys and never reads, then {c0['nsets']} sets; items aged {c0['age_s']} s "
            f"before the writes.", "",
            "| metric | parent 4234cbad76c9 | fix f2a4e5b491ed |", "|---|---|---|"]
    by = {arm: [r for r in rs if r["arm"] == arm] for arm in ("parent", "fix")}
    out.append(f"| repetitions | {len(by['parent'])} | {len(by['fix'])} |")
    for m, fmt in M:
        cells = []
        for arm in ("parent", "fix"):
            xs = [r.get(m) for r in by[arm]]
            if m == "first_ok_index":
                cells.append(", ".join("none" if x is None else str(x) for x in xs))
                continue
            xs = [x for x in xs if x is not None]
            if not xs:
                cells.append("-")
                continue
            sd = st.stdev(xs) if len(xs) > 1 else 0.0
            cells.append(f"{fmt % st.mean(xs)} sd {fmt % sd} [{fmt % min(xs)}, {fmt % max(xs)}]")
        out.append(f"| {m} | {cells[0]} | {cells[1]} |")
    out.append("")
open(os.path.join(D, "results.md"), "w").write("\n".join(out) + "\n")
print("\n".join(out))
